"""Render the pipeline registry into Mermaid + Markdown tables for the README.

Nothing here is hand-maintained: `python -m src.pipeline graph` regenerates the
chart and the tables from the registry and the provenance manifests.
"""

import re
from pathlib import Path

from src.pipeline import provenance as prov
from src.pipeline.registry import PLANNED, STAGES, WIP, Stage, topological_order
from src.pipeline.runner import status

START = "<!-- PIPELINE:START -->"
END = "<!-- PIPELINE:END -->"

GROUP_LABEL = {"data": "Data preparation", "qc": "Quality control / leakage gates",
               "features": "Feature engineering", "models": "Baseline models",
               "tsfm": "Foundation-model track (planned)"}


def _node_id(text: str) -> str:
    """Mermaid-safe node id."""
    return "n_" + re.sub(r"[^0-9a-zA-Z]+", "_", text).strip("_")


def _artifact_label(path: str) -> str:
    """Short, readable label for an artifact path."""
    short = path.replace("data/", "").replace("outputs/", "")
    return short.replace("_", " ") if len(short) < 34 else short[:31] + "…"


def mermaid() -> str:
    """Build the Mermaid flowchart of artifacts and stages.

    Returns:
        A fenced Mermaid code block as a string.
    """
    lines = ["```mermaid", "flowchart LR"]
    seen: set[str] = set()

    for group in ("data", "features", "models", "tsfm", "qc"):
        members = [s for s in STAGES if s.group == group]
        if not members:
            continue
        lines.append(f'  subgraph {_node_id(group)}["{GROUP_LABEL[group]}"]')
        for stage in members:
            lines.append(f'    {_node_id(stage.name)}["{stage.name}"]')
        lines.append("  end")

    for stage in STAGES:
        sid = _node_id(stage.name)
        for item in stage.inputs:
            aid = _node_id(item)
            if aid not in seen:
                lines.append(f'  {aid}[("{_artifact_label(item)}")]')
                seen.add(aid)
            lines.append(f"  {aid} --> {sid}")
        for item in stage.outputs:
            aid = _node_id(item)
            if aid not in seen:
                lines.append(f'  {aid}[("{_artifact_label(item)}")]')
                seen.add(aid)
            lines.append(f"  {sid} --> {aid}")

    lines += [
        "  classDef built fill:#2B3A42,stroke:#2B3A42,color:#ffffff;",
        "  classDef planned fill:#ffffff,stroke:#6B7A82,color:#6B7A82,stroke-dasharray: 4 3;",
        "  classDef wip fill:#E8A33D,stroke:#A86A12,color:#2B3A42;",
        "  classDef artifact fill:#FDF4E6,stroke:#A86A12,color:#2B3A42;",
    ]
    for status_name in (PLANNED, WIP, "built"):
        names = [_node_id(s.name) for s in STAGES if s.status == status_name]
        if names:
            lines.append(f"  class {','.join(names)} {status_name};")
    if seen:
        lines.append(f"  class {','.join(sorted(seen))} artifact;")
    lines.append("```")
    return "\n".join(lines)


def status_table() -> str:
    """Markdown table of stage freshness, last run and commit."""
    flag = {"fresh": "🟢", "stale": "🟡", "planned": "⬜"}
    rows = ["| | Stage | Group | State | Last run (UTC) | Commit | Took |",
            "|---|---|---|---|---|---|---|"]
    for row in status():
        rows.append(f"| {flag[row['state']]} | `{row['stage']}` | {row['group']} | "
                    f"{row['state']} — {row['reason']} | {row['last_run']} | "
                    f"`{row['commit']}` | {row['duration']} |")
    return "\n".join(rows)


def lineage_table() -> str:
    """Markdown table of each stage's inputs, outputs and key parameters."""
    rows = ["| Stage | Inputs | Outputs | Key parameters |", "|---|---|---|---|"]
    for stage in topological_order():
        params = ", ".join(f"{k}={v}" for k, v in stage.params.items()
                           if not isinstance(v, list) or len(v) < 6) or "—"
        rows.append(f"| `{stage.name}` | {_paths(stage.inputs)} | "
                    f"{_paths(stage.outputs)} | {params[:90]} |")
    return "\n".join(rows)


def _paths(items: tuple[str, ...]) -> str:
    """Format a tuple of paths as inline code, or an em dash."""
    return "<br>".join(f"`{i}`" for i in items) if items else "—"


def block() -> str:
    """The complete generated README section."""
    commit, branch, dirty = prov.git_state()
    return "\n\n".join([
        START,
        "## Pipeline overview",
        "_Auto-generated by `python -m src.pipeline graph` — do not edit by hand._",
        mermaid(),
        "### Stage status",
        status_table(),
        "### Data lineage",
        lineage_table(),
        f"_Rendered at commit `{commit[:7]}`"
        f"{' (working tree dirty)' if dirty else ''} on branch `{branch}`._",
        END,
    ])


def inject(readme: Path) -> Path:
    """Write the generated block into README between the markers.

    Args:
        readme: path to the README file.

    Returns:
        The path written.
    """
    text = readme.read_text() if readme.exists() else "# TruckIDMe\n"
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        text = head + block() + tail
    else:
        text = text.rstrip() + "\n\n" + block() + "\n"
    readme.write_text(text)
    return readme
