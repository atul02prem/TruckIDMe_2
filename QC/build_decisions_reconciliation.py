"""Generate the reconciliation table for DECISIONS.md from the measurement reports.

Every one of the 102 CAN signals appears with its type, its type-matched statistic,
its status before this decision and after it. Transcribing 102 rows by hand is how
a drop list that collapses the channel set to 4 signals gets accepted, so the table
is built from the reports and the config rather than written out.
"""
from __future__ import annotations

import re
from pathlib import Path

from src.config import EXCLUDE_SPNS, OUT_REPORTS

CLASSIFICATION = OUT_REPORTS / "signal_classification.md"
CONTINUOUS = OUT_REPORTS / "continuous_separability.md"
STEP = OUT_REPORTS / "step_separability.md"
EVENT = OUT_REPORTS / "event_presence.md"

OUT_PATH = Path("outputs/reports/decisions_reconciliation.md")

# Signals this decision excludes that EXCLUDE_SPNS does not yet contain.
NEWLY_EXCLUDED: dict[int, str] = {
    5015: "constant — one value across 12,931,907 samples, 46/46 drivers",
    3229: "warm-up missingness fingerprint (0–26.18% per drive, 57.7% in first 10%)",
    3230: "warm-up missingness fingerprint (0–26.18% per drive, 57.7% in first 10%)",
    3231: "warm-up missingness fingerprint (0–26.18% per drive, 57.7% in first 10%)",
    3232: "enumerated diagnostic code (FMI) + warm-up missingness fingerprint",
    3239: "dew point is a weather variable — ambient family",
    2978: "accessory/thermal load, not driver input — fan + electrical family",
    515: "ECU setpoint, not a driver input; 99.22% one value; ramp absent in 9/46 drives",
    4154: "9.31% of samples exceed the published 0-0.875% range by 15-158x; decode broken",
}

# Signals kept only once a stated precondition is met.
CONDITIONAL: dict[int, str] = {
    2979: "keep only after sentinel -> NaN and ZOH aggregation; unusable until then",
}


def parse_classification() -> dict[int, dict[str, str]]:
    """Read SPN -> type/coverage/distinct from the classification report's All-signals table."""
    rows: dict[int, dict[str, str]] = {}
    in_table = False
    for line in CLASSIFICATION.read_text().splitlines():
        if line.startswith("## All signals"):
            in_table = True
            continue
        if in_table and line.startswith("## "):
            break
        if not in_table or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 4 or not cells[0].isdigit():
            continue
        rows[int(cells[0])] = {
            "name": cells[1].strip("`"),
            "type": cells[2],
            "coverage": cells[3],
            "distinct": cells[4],
        }
    return rows


def parse_statistic(path: Path, heading: str, columns: dict[str, int]) -> dict[int, dict[str, str]]:
    """Read SPN -> named statistic cells from one report's full table."""
    rows: dict[int, dict[str, str]] = {}
    in_table = False
    for line in path.read_text().splitlines():
        if line.startswith(heading):
            in_table = True
            continue
        if in_table and line.startswith("## "):
            break
        if not in_table or not line.startswith("|"):
            continue
        cells = [c.strip() for c in line.strip("|").split("|")]
        if len(cells) < 3 or not cells[1].isdigit():
            continue
        rows[int(cells[1])] = {
            label: cells[idx].strip("*") for label, idx in columns.items() if idx < len(cells)
        }
    return rows


def headline(spn: int, kind: str, cont: dict, step: dict, event: dict) -> str:
    """One statistic string per signal, chosen by the signal's own type."""
    if kind == "continuous" and spn in cont:
        r = cont[spn]
        return f"η² raw {r['raw']} · window {r['window']}"
    if kind == "step" and spn in step:
        r = step[spn]
        return f"Cramér's V {r['v']} · Theil's U {r['u']}"
    if kind == "event" and spn in event:
        r = event[spn]
        return f"coverage {r['coverage']} · sd {r['sd']} · η² rate {r['eta']}"
    return "—"


def build() -> str:
    classes = parse_classification()
    cont = parse_statistic(
        CONTINUOUS, "## All continuous signals", {"raw": 3, "window": 4, "mi": 5}
    )
    step = parse_statistic(STEP, "## All step signals", {"states": 3, "v": 4, "u": 5})
    event = parse_statistic(
        EVENT, "## All event signals", {"coverage": 3, "sd": 4, "eta": 5}
    )

    proposed = set(EXCLUDE_SPNS) | set(NEWLY_EXCLUDED)

    lines = [
        "# Reconciliation — every CAN signal, before and after",
        "",
        f"Generated by `QC/build_decisions_reconciliation.py`. **{len(classes)} signals.** "
        f"Excluded **{len(EXCLUDE_SPNS)} → {len(proposed)}**; "
        f"model channels **{len(classes) - len(EXCLUDE_SPNS)} → {len(classes) - len(proposed)}**.",
        "",
        "The channel count is stated above so that a drop list which collapses the input set "
        "cannot be adopted unnoticed. Each row carries the statistic that applies to that "
        "signal's type — never η² on a gear.",
        "",
        "Change column: ➕ newly excluded · ⚠️ kept subject to a precondition · "
        "· (no change).",
        "",
        "| Change | SPN | Signal | Type | Statistic (type-matched) | Before | After | Basis for the change |",
        "|:-:|--:|---|---|---|:-:|:-:|---|",
    ]

    def sort_key(spn: int) -> tuple:
        changed = spn in NEWLY_EXCLUDED or spn in CONDITIONAL
        return (0 if changed else 1, classes[spn]["type"], spn)

    for spn in sorted(classes, key=sort_key):
        info = classes[spn]
        before = "EXCL" if spn in EXCLUDE_SPNS else "keep"
        after = "EXCL" if spn in proposed else "keep"
        if spn in NEWLY_EXCLUDED:
            mark, basis = "➕", NEWLY_EXCLUDED[spn]
        elif spn in CONDITIONAL:
            mark, basis = "⚠️", CONDITIONAL[spn]
        else:
            mark, basis = "·", ""
        stat = headline(spn, info["type"], cont, step, event)
        lines.append(
            f"| {mark} | {spn} | `{info['name']}` | {info['type']} | {stat} | "
            f"{before} | {after} | {basis} |"
        )

    missing = sorted(proposed - set(classes))
    lines += [
        "",
        "## Integrity checks on this table",
        "",
        f"- signals classified: **{len(classes)}** (expected 102)",
        f"- every proposed exclusion exists as a measured signal: "
        f"**{'yes' if not missing else 'NO — ' + str(missing)}**",
        f"- exclusions that are new: **{len(NEWLY_EXCLUDED)}** "
        f"({', '.join(str(s) for s in sorted(NEWLY_EXCLUDED))})",
        f"- signals de-excluded (EXCL → keep): **{len(set(EXCLUDE_SPNS) - proposed)}** "
        "— nothing is being re-introduced by this decision",
        f"- kept subject to a precondition: **{len(CONDITIONAL)}** "
        f"({', '.join(str(s) for s in sorted(CONDITIONAL))})",
    ]
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT_PATH.write_text(build())
    print(f"report -> {OUT_PATH}")


if __name__ == "__main__":
    main()
